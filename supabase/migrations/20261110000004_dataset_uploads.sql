-- Dataset upload catalog and row-level quality results.
-- Additive migration; existing platform records are not changed.

CREATE TABLE IF NOT EXISTS public.uploaded_datasets (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    original_filename TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    file_format TEXT NOT NULL CHECK (file_format IN ('csv', 'xlsx', 'xls', 'json')),
    energy_source TEXT NOT NULL
        CHECK (energy_source IN ('solar', 'wind', 'hydropower', 'geothermal', 'biomass', 'other')),
    file_size_bytes BIGINT NOT NULL CHECK (file_size_bytes > 0),
    sha256 TEXT NOT NULL,
    storage_location TEXT NOT NULL,
    processing_status TEXT NOT NULL DEFAULT 'queued'
        CHECK (processing_status IN ('queued', 'validating', 'processing', 'persisting', 'completed', 'failed', 'cancelled')),
    progress_stage TEXT NOT NULL DEFAULT 'upload_complete',
    total_records BIGINT NOT NULL DEFAULT 0,
    valid_records BIGINT NOT NULL DEFAULT 0,
    warning_records BIGINT NOT NULL DEFAULT 0,
    invalid_records BIGINT NOT NULL DEFAULT 0,
    duplicate_records BIGINT NOT NULL DEFAULT 0,
    missing_values JSONB NOT NULL DEFAULT '{}'::jsonb,
    schema_report JSONB NOT NULL DEFAULT '{}'::jsonb,
    quality_report JSONB NOT NULL DEFAULT '{}'::jsonb,
    analytics JSONB NOT NULL DEFAULT '{}'::jsonb,
    processing_duration_seconds DOUBLE PRECISION,
    processing_error TEXT,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (owner_id, sha256)
);

CREATE TABLE IF NOT EXISTS public.uploaded_dataset_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id UUID NOT NULL REFERENCES public.uploaded_datasets(id) ON DELETE CASCADE,
    row_number BIGINT NOT NULL,
    classification TEXT NOT NULL CHECK (classification IN ('valid', 'warning', 'invalid', 'duplicate')),
    issues JSONB NOT NULL DEFAULT '[]'::jsonb,
    record JSONB NOT NULL CHECK (jsonb_typeof(record) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (dataset_id, row_number)
);

CREATE INDEX IF NOT EXISTS idx_uploaded_datasets_owner_uploaded
    ON public.uploaded_datasets (owner_id, uploaded_at DESC);
CREATE INDEX IF NOT EXISTS idx_uploaded_datasets_owner_status
    ON public.uploaded_datasets (owner_id, processing_status);
CREATE INDEX IF NOT EXISTS idx_uploaded_dataset_records_page
    ON public.uploaded_dataset_records (dataset_id, row_number);
CREATE INDEX IF NOT EXISTS idx_uploaded_dataset_records_classification
    ON public.uploaded_dataset_records (dataset_id, classification, row_number);

CREATE OR REPLACE FUNCTION public.set_uploaded_dataset_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at := pg_catalog.now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER set_uploaded_dataset_updated_at
    BEFORE UPDATE ON public.uploaded_datasets
    FOR EACH ROW EXECUTE FUNCTION public.set_uploaded_dataset_updated_at();

ALTER TABLE public.uploaded_datasets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.uploaded_dataset_records ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Owners can read uploaded datasets"
    ON public.uploaded_datasets FOR SELECT TO authenticated
    USING (owner_id = (SELECT auth.uid()));
CREATE POLICY "Owners can read their dataset records"
    ON public.uploaded_dataset_records FOR SELECT TO authenticated
    USING (EXISTS (
        SELECT 1 FROM public.uploaded_datasets AS d
        WHERE d.id = dataset_id AND d.owner_id = (SELECT auth.uid())
    ));

GRANT SELECT ON public.uploaded_datasets, public.uploaded_dataset_records TO authenticated;
GRANT ALL ON public.uploaded_datasets, public.uploaded_dataset_records TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.uploaded_dataset_records_id_seq TO service_role;
GRANT EXECUTE ON FUNCTION public.set_uploaded_dataset_updated_at() TO service_role;
